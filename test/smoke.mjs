import { createRequire } from "node:module";
import { serve, loadPlaywright } from "./serve.mjs";
const require = createRequire(import.meta.url);
const { chromium } = loadPlaywright();
const srv = await serve(process.argv[2] ? (await import("node:path")).resolve(process.argv[2]) : (await import("node:path")).resolve("dist"), 8765);
const browser = await chromium.launch({ args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist"] });
const page = await browser.newPage({ viewport: { width: 1366, height: 768 } });
const errs = [];
page.on("console", (m) => { if (m.type() === "error" || m.type() === "warning") errs.push(m.type() + ": " + m.text()); });
page.on("pageerror", (e) => errs.push("pageerror: " + e.message + "\n" + e.stack));
await page.goto("http://localhost:8765/");
await page.waitForSelector("#menu:not([hidden])", { timeout: 60000 }).catch(() => {});
await page.screenshot({ path: "/tmp/df_menu.png" });
await page.click("#mNew"); await page.click('[data-diff="medium"]');
await page.waitForSelector("#campaign:not([hidden])");
await page.screenshot({ path: "/tmp/df_campaign.png" });
await page.click('[data-op="op01"]');
await page.waitForSelector("#briefing:not([hidden])");
await page.screenshot({ path: "/tmp/df_brief.png" });
await page.click("#bDeploy");
const tdep = Date.now(); await page.waitForFunction(() => window.__df && window.__df.session.game, null, { timeout: 120000 }); console.log("deploy ms", Date.now() - tdep); await page.waitForTimeout(1500);
await page.screenshot({ path: "/tmp/df_game.png" });
const info = await page.evaluate(() => { const a = window.__df, g = a.session.game; return { units: g.units.length, zombies: g.zombies.length, civs: g.civs.length, nests: g.nests.length, obj: g.mission.active.map(o => o.id + ':' + o.progress), cam: [a.session.cam.x, a.session.cam.y, a.session.cam.zoom], time: g.time, paths: g.paths.stats }; });
console.log(JSON.stringify(info));
console.log(errs.slice(0, 20).join("\n"));
await browser.close(); srv.close();
